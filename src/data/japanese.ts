/** For the taxi card: the first name in a "A · B" list is the destination. */
export function taxiTarget(place: string): string | undefined {
  const ja = PLACE_JA[place];
  if (!ja) return undefined;
  const first = ja.split(" · ")[0];
  return first.includes("→") ? first.split("→").pop()!.trim() : first;
}

